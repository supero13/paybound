// Copies compiled ABIs from contracts/out into web/src/abi and assistant/src/abi.
// Run after `forge build`:  node scripts/export-abi.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
const names = ["PayboundVault", "PayeeRegistry"];
for (const dest of ["web/src/abi", "assistant/src/abi"]) {
  mkdirSync(dest, { recursive: true });
  for (const n of names) {
    const { abi } = JSON.parse(readFileSync(`contracts/out/${n}.sol/${n}.json`, "utf8"));
    writeFileSync(`${dest}/${n}.ts`, `// Generated by scripts/export-abi.mjs. Do not edit.\nexport const ${n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`);
  }
}
console.log("ABIs exported");
